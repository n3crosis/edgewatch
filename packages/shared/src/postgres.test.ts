import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { type PgClient, type PgRows, postgresDatabase } from './postgres';
import { toPostgres, toPostgresSchema } from './sql-dialect';

it('keeps numeric CASE sums intact instead of treating them as booleans', () => {
  const sql = 'SELECT sum(CASE WHEN status_code >= 500 THEN 1 ELSE 0 END) AS errors FROM traces';
  expect(toPostgres(sql)).toBe(sql);
});

describe('toPostgres', () => {
  it('numbers bare and indexed parameters like SQLite', () => {
    expect(toPostgres('SELECT * FROM t WHERE a = ? AND b = ? LIMIT ?')).toBe('SELECT * FROM t WHERE a = $1 AND b = $2 LIMIT $3');
    expect(toPostgres('VALUES (?1, ?2), (?2, ?)')).toBe('VALUES ($1, $2), ($2, $3)');
  });

  it('leaves string literals and quoted identifiers alone', () => {
    expect(toPostgres(`SELECT 'what? user rowid' AS "user", x FROM t WHERE y = ?`)).toBe(`SELECT 'what? user rowid' AS "user", x FROM t WHERE y = $1`);
    expect(toPostgres(`SELECT 'it''s?' FROM t WHERE y = ?`)).toBe(`SELECT 'it''s?' FROM t WHERE y = $1`);
  });

  it('types parameters compared only with NULL', () => {
    expect(toPostgres('SELECT 1 FROM t WHERE ? IS NULL AND ? IS NOT NULL')).toBe('SELECT 1 FROM t WHERE $1::text IS NULL AND $2::text IS NOT NULL');
  });

  it('turns INSERT OR IGNORE into ON CONFLICT DO NOTHING', () => {
    expect(toPostgres('INSERT OR IGNORE INTO projects (id, name) VALUES (?, ?);')).toBe('INSERT INTO projects (id, name) VALUES ($1, $2) ON CONFLICT DO NOTHING');
  });

  it('rewrites group_concat, two-argument max/min and GROUP BY hints', () => {
    expect(toPostgres('SELECT group_concat(DISTINCT method), group_concat(x, ?) FROM t GROUP BY +route')).toBe(
      "SELECT string_agg(DISTINCT CAST(method AS text), ','), string_agg(CAST(x AS text), $1) FROM t GROUP BY route",
    );
    expect(toPostgres('SET m = max(m, excluded.m), n = min(a, max(b, c)), o = max(d)')).toBe('SET m = greatest(m, excluded.m), n = least(a, greatest(b, c)), o = max(d)');
  });

  it('sums comparisons as 0/1 like SQLite and leaves plain sums alone', () => {
    expect(toPostgres("SELECT sum(type = 'hit'), sum(coalesce(code, 0) != 0), sum(a IN (1, 2)), sum(x IS NULL OR y > 1), sum(duration_ms), sum(coalesce(a, 0))")).toBe(
      "SELECT sum(CASE WHEN type = 'hit' THEN 1 ELSE 0 END), sum(CASE WHEN coalesce(code, 0) != 0 THEN 1 ELSE 0 END), sum(CASE WHEN a IN (1, 2) THEN 1 ELSE 0 END), " +
        'sum(CASE WHEN x IS NULL OR y > 1 THEN 1 ELSE 0 END), sum(duration_ms), sum(coalesce(a, 0))',
    );
  });

  it('quotes reserved and mixed-case names and maps rowid, CAST and LIKE', () => {
    expect(toPostgres('SELECT user, excluded.user, users.id AS userId FROM users WHERE name LIKE ? AND user ILIKE ?')).toBe(
      'SELECT "user", excluded."user", users.id AS "userId" FROM users WHERE name ILIKE $1 AND "user" ILIKE $2',
    );
    expect(toPostgres('DELETE FROM t WHERE rowid IN (SELECT rowid FROM t LIMIT ?) AND CAST(x AS INTEGER) > 0')).toBe(
      'DELETE FROM t WHERE ctid IN (SELECT ctid FROM t LIMIT $1) AND CAST(x AS BIGINT) > 0',
    );
  });

  it('keeps unbalanced input unchanged', () => {
    expect(toPostgres('SELECT max(a, b')).toBe('SELECT max(a, b');
  });
});

describe('toPostgresSchema', () => {
  it('maps column types, identity keys, reserved names and the timestamp default', () => {
    const out = toPostgresSchema(
      "-- note: user INTEGER\nCREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER, r REAL, user TEXT, at TEXT DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')));",
    );
    expect(out).toBe(
      `\nCREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT, r DOUBLE PRECISION, "user" TEXT, at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')));`,
    );
  });

  it('leaves no SQLite-only types in any migration', () => {
    const dir = join(__dirname, '../../../workers/migrations');
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql'))) {
      const out = toPostgresSchema(readFileSync(join(dir, file), 'utf8'));
      expect(out, file).not.toMatch(/\b(INTEGER|REAL|AUTOINCREMENT|strftime)\b/i);
      expect(out, file).not.toMatch(/(?<!["\w])user(?!["\w])/);
    }
  });
});

function fakeClient(rows: PgRows = [], calls: { text: string; params: unknown[]; tx: boolean }[] = []): PgClient {
  const make = (tx: boolean): PgClient => ({
    query: async (text, params) => {
      calls.push({ text, params, tx });
      return rows;
    },
    transaction: async (fn) => fn(make(true)),
  });
  return make(false);
}

describe('postgresDatabase', () => {
  it('translates, binds like D1 and reads results', async () => {
    const calls: { text: string; params: unknown[]; tx: boolean }[] = [];
    const rows: PgRows = Object.assign([{ n: 3, name: 'a' }], { count: 2 });
    const db = postgresDatabase(fakeClient(rows, calls));
    const stmt = db.prepare('SELECT n, name FROM t WHERE a = ? AND b = ?').bind(true, false);
    expect(await stmt.first<number>('n')).toBe(3);
    expect(await stmt.first<number>('missing')).toBeNull();
    expect(await stmt.first()).toEqual({ n: 3, name: 'a' });
    expect(await stmt.all()).toEqual({ results: [{ n: 3, name: 'a' }], meta: { changes: 2 } });
    expect((await stmt.run()).meta.changes).toBe(2);
    expect(calls[0]).toEqual({ text: 'SELECT n, name FROM t WHERE a = $1 AND b = $2', params: [1, 0], tx: false });
    expect(() => db.prepare('SELECT ?').bind(undefined)).toThrow(TypeError);
  });

  it('returns null from first() with no rows and zero changes without a count', async () => {
    const db = postgresDatabase(fakeClient([]));
    expect(await db.prepare('SELECT 1').first()).toBeNull();
    expect((await db.prepare('DELETE FROM t').run()).meta.changes).toBe(0);
  });

  it('runs a batch in one transaction and rejects foreign statements', async () => {
    const calls: { text: string; params: unknown[]; tx: boolean }[] = [];
    const db = postgresDatabase(fakeClient([], calls));
    const results = await db.batch([db.prepare('INSERT INTO t VALUES (?)').bind(1), db.prepare('DELETE FROM t')]);
    expect(results).toHaveLength(2);
    expect(calls.map((c) => [c.text, c.tx])).toEqual([
      ['INSERT INTO t VALUES ($1)', true],
      ['DELETE FROM t', true],
    ]);
    const foreign = { bind: () => foreign, first: async () => null, all: async () => ({ results: [], meta: {} }), run: async () => ({ results: [], meta: {} }) };
    await expect(db.batch([foreign])).rejects.toThrow('same database');
  });
});
